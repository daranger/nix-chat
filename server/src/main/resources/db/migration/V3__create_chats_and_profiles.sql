-- Chats (Alisher): conversations, their members and messages.
-- user_id / sender_id point to users.id, the account that logged in with JWT.
CREATE TABLE conversations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_chat BOOLEAN      NOT NULL,
    title      VARCHAR(128),
    created_at TIMESTAMP    NOT NULL
);

CREATE TABLE conversation_members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT    NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    user_id         BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    joined_at       TIMESTAMP NOT NULL,
    CONSTRAINT uq_conversation_member UNIQUE (conversation_id, user_id)
);
CREATE INDEX idx_conversation_members_user ON conversation_members (user_id);

CREATE TABLE messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT    NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content         TEXT      NOT NULL,
    sent_at         TIMESTAMP NOT NULL
);
CREATE INDEX idx_messages_conversation ON messages (conversation_id, id);

-- User profiles and contacts (Alisher)
CREATE TABLE user_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(32)  NOT NULL UNIQUE,
    username     VARCHAR(32)  UNIQUE,
    display_name VARCHAR(64)  NOT NULL,
    bio          VARCHAR(255),
    avatar_url   VARCHAR(512),
    created_at   DATE         NOT NULL
);

CREATE TABLE contacts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT NOT NULL REFERENCES user_profiles (id) ON DELETE CASCADE,
    contact_user_id BIGINT NOT NULL REFERENCES user_profiles (id) ON DELETE CASCADE,
    alias           VARCHAR(64),
    created_at      DATE   NOT NULL,
    CONSTRAINT uq_contact UNIQUE (owner_id, contact_user_id)
);
